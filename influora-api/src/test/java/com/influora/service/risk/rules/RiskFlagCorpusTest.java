    private static final Pattern FLAG_HEADING = Pattern.compile("^##\\s*Flag\\s*\\d+:\\s*(\\S+)");
    private static final Pattern LABEL_HEADING = Pattern.compile("^###\\s*SHOULD\\s*(NOT\\s*)?FLAG");
    private static final Pattern ROW_ID = Pattern.compile("^[A-Z]+-[A-Z]-\\d+$");

    /** Mirrors gen_nisha_blind_tsv.py's `parse()` exactly, so both must agree or this test finds it. */
    private static List<Row> parseNishaMarkdown(String mdText) {
        List<Row> rows = new ArrayList<>();
        String rule = null;
        Boolean expectFlag = null;
        for (String rawLine : mdText.split("\n", -1)) {
            String line = rawLine.strip();
            Matcher fm = FLAG_HEADING.matcher(line);
            if (fm.find()) {
                rule = fm.group(1);
                continue;
            }
            Matcher lm = LABEL_HEADING.matcher(line);
            if (lm.find()) {
                expectFlag = lm.group(1) == null;
                continue;
            }
            if (!line.startsWith("|")) {
                continue;
            }
            String trimmed = line;
            if (trimmed.startsWith("|")) trimmed = trimmed.substring(1);
            if (trimmed.endsWith("|")) trimmed = trimmed.substring(0, trimmed.length() - 1);
            String[] cells = trimmed.split("\\|", -1);
            if (cells.length < 6) {
                continue;
            }
            for (int i = 0; i < cells.length; i++) {
                cells[i] = cells[i].strip();
            }
            String rowId = cells[0];
            if (!ROW_ID.matcher(rowId).matches()) {
                continue;
            }
            if (rule == null || expectFlag == null) {
                throw new IllegalStateException("row " + rowId + " appears before a Flag/SHOULD-FLAG heading");
            }
            String language = cells[1];
            String text = cells[2];
            if (text.length() >= 2 && text.startsWith("\"") && text.endsWith("\"")) {
                text = text.substring(1, text.length() - 1);
            }
            rows.add(new Row(rowId, rule, language, text, expectFlag, "nisha_blind"));
        }
        return rows;
    }

