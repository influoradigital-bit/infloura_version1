    @Test
    @DisplayName("K-2b report: TP/FP/TN/FN, precision and recall per rule, ALL vs. nisha_blind vs. everyone else")
    void printFullReport() {
        System.out.println("==== K-2b corpus report (round 5, verbatim Nisha rows) ====");
        for (String rule : List.of(HD, OP)) {
            System.out.println("-- " + rule + " --");
            printGroup(rule, "ALL", r -> true);
            printGroup(rule, "nisha_blind only", r -> r.source().equals("nisha_blind"));
            printGroup(rule, "non-blind (kabir/round4/trigger_text)", r -> !r.source().equals("nisha_blind"));
        }
    }

    private static void printGroup(String rule, String label, Predicate<Row> filter) {
        int tp = 0, fp = 0, tn = 0, fn = 0;
        List<String> fpIds = new ArrayList<>();
        List<String> fnIds = new ArrayList<>();
        for (Row r : CORPUS) {
            if (!r.rule().equals(rule) || !filter.test(r)) continue;
            boolean got = matches(r.rule(), r.text());
            if (r.expectFlag() && got) tp++;
            else if (!r.expectFlag() && got) { fp++; fpIds.add(r.id()); }
            else if (!r.expectFlag()) tn++;
            else { fn++; fnIds.add(r.id()); }
        }
        int total = tp + fp + tn + fn;
        if (total == 0) return;
        double precision = (tp + fp) == 0 ? Double.NaN : (double) tp / (tp + fp);
        double recall = (tp + fn) == 0 ? Double.NaN : (double) tp / (tp + fn);
        System.out.printf(
                "  [%s] n=%d TP=%d FP=%d TN=%d FN=%d precision=%.3f recall=%.3f%n",
                label, total, tp, fp, tn, fn, precision, recall);
        if (!fpIds.isEmpty()) System.out.println("    FP ids: " + fpIds);
        if (!fnIds.isEmpty()) System.out.println("    FN ids: " + fnIds);
    }

