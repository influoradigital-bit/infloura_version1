    /**
     * K-2c / LOW (a) (Ruling 3a): {@link OffPlatformPaymentRule#PAIRING_WINDOW} pinned to exactly 6
     * tokens, with neutral filler and no real wallet/request vocabulary in the gap, so the test is
     * about the window, not about corpus wording. The distances below are the LITERALS 6 and 7, not
     * {@code PAIRING_WINDOW} or {@code PAIRING_WINDOW + 1} — writing them as the constant would pass
     * whatever the constant says and pin nothing.
     */
    @Test
    @DisplayName("K-2c / LOW (a): the pairing window is exactly 6 tokens, in both directions and for a two-word wallet name")
    void pairingWindowIsExactlySix() {
        String[] filler = {"alpha", "bravo", "charlie", "delta", "echo", "foxtrot"};
        String gapSix = String.join(" ", filler[0], filler[1], filler[2], filler[3], filler[4]); // 5 words -> distance 6
        String gapSeven = String.join(" ", filler); // 6 words -> distance 7

        List<String> failures = new ArrayList<>();
        if (!matches(OP, "upi " + gapSix + " send")) failures.add("wallet..request at distance 6 must flag");
        if (!matches(OP, "send " + gapSix + " upi")) failures.add("request..wallet at distance 6 must flag");
        if (!matches(OP, "google pay " + gapSix + " send")) failures.add("two-word wallet name at distance 6 must flag");
        if (matches(OP, "upi " + gapSeven + " send")) failures.add("wallet..request at distance 7 must not flag");
        if (matches(OP, "send " + gapSeven + " upi")) failures.add("request..wallet at distance 7 must not flag");
        if (matches(OP, "google pay " + gapSeven + " send")) failures.add("two-word wallet name at distance 7 must not flag");

        assertThat(failures).as("PAIRING_WINDOW must be exactly 6 tokens").isEmpty();
    }

    /**
     * K-2c (round 6, Ruling 1): a dedicated, named check of the sentence-boundary rule itself, on
     * top of the whole-corpus ratchet and zero-false-positive tests those same rows also feed.
     * Kept separate so a reviewer reading red output sees "sentence boundary" failures grouped, not
     * mixed into the full corpus report.
     */
    @Test
    @DisplayName("K-2c: pairing does not cross a sentence end, but a protected dot, an abbreviation or a hard line-wrap does not count as one")
    void sentenceBoundaryStopsPairingAcrossSentences() {
        List<String> failures = new ArrayList<>();
        for (String id : List.of("XS-1", "XS-2", "XS-3", "XS-4", "XS-5", "XS-6")) {
            if (matches(OP, byId(OP, id).text())) {
                failures.add(id + " must not flag: pairing must not cross a sentence end");
            }
        }
        for (String id : List.of(
                "AB-rs", "AB-inr", "AB-rupee-sym", "AB-ac-no", "AB-amt", "AB-eg",
                "NL-hardwrap-ask", "NL-hardwrap-ask-2")) {
            if (!matches(OP, byId(OP, id).text())) {
                failures.add(id + " must still flag: not a real sentence end");
            }
        }
        if (matches(OP, byId(OP, "NL-bullets").text())) {
            failures.add("NL-bullets must not flag: a line break into a list item is a sentence end");
        }
        assertThat(failures).as("K-2c sentence-boundary behaviour").isEmpty();
    }

